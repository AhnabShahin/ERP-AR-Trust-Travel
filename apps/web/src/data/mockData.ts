export const getServiceTypeForCategory = (category: string, isMultiDay?: boolean): ServiceMainType => {
  if (isMultiDay || category === 'Holiday Package' || category.toLowerCase().includes('package')) {
    return 'Tour Package';
  }
  const cat = category.toLowerCase();
  const transferKeywords = ['airport transit', 'vip chauffeur', 'transit express', 'transfer', 'chauffeur', 'limousine'];
  if (transferKeywords.some((k) => cat.includes(k))) {
    return 'Transfer Service';
  }
  return 'Tour Service';
};

