/** Mounts every resource router under /api/<path>. */
export function registerResourceRoutes(app: Express) {
  for (const def of resources) {
    const createSchema = z.object(def.shape);
    app.use(
      `/api/${def.path}`,
      createCrudRouter({
        name: def.name,
        delegate: def.delegate as unknown as CrudDelegate,
        createSchema,
        updateSchema: createSchema.partial(),
        searchFields: def.searchFields,
        filterFields: def.filterFields,
        defaultOrderBy: def.defaultOrderBy,
        publicRead: def.publicRead,
        audit: def.audit,
      })
    );
  }
}

/** Exposes the list of mounted resource paths (handy for a root index route). */
export const resourcePaths = resources.map((r) => r.path);
